#!/bin/bash

# ڕەنگی سەوز بۆ نیشاندانی سەرکەوتن
GREEN='\033[0;32m'
NC='\033[0m' # No Color

echo -e "${GREEN}🎬 TMX-STATE: سێرڤەرەکە ئێستا چالاکە و هیچ هێزێک نایوەستێنێت...${NC}"
echo "بۆ وەستاندنی یەکجاری، Ctrl + C دابگرە."

# ئەمە ئەو "Loop"ەیە کە ناهێڵێت سێرڤەرەکە بمرێت
while true
do
    # لێرەدا سێرڤەرە سەرەکییەکە کار پێ دەکەین
    python -m http.server 8888
    
    # ئەگەر سێرڤەرەکە بە هەر هۆکارێک کێشەی بۆ دروست بوو، لێرەدا دووبارە دەست پێ دەکاتەوە
    echo -e "${GREEN}⚠️ ئاگاداری: هەوڵی وەستاندنی سێرڤەر درا، بەڵام TMX-STATE ڕێگری کرد! دووبارە چالاک دەبێتەوە...${NC}"
    sleep 1
done
