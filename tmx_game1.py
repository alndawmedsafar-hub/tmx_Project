def start_game():
    print("\n\033[1;32m[+] سێرڤەری TMX چالاکە...")
    print("\033[1;37m" + "="*50)
    print("بەخێربێیت بۆ یارییە نوێیەکەت فەرماندە!")
    print("="*50)
    
    # لێرەدا دەتوانیت کۆدی یاری دۆمینە یان هەر یارییەکی تر کە ویستت دابنێیت
    print("\n\033[1;36m[1] دەستپێکردنی یاری (START)")
    print("[2] زانیاری پڕۆژە (INFO)")
    print("[3] چوونە دەرەوە (EXIT)")
    
    cmd = input("\n\033[1;33mبڕیار بدە فەرماندە: ")
    if cmd == "1":
        print("\n\033[1;32mیاری دەستی پێکرد... ئامادەبە!")
    elif cmd == "2":
        print("\n\033[1;37mئەم یارییە لەلایەن گەنجێکی کوردەوە بۆ تێرموکس دروستکراوە.")
    else:
        sys.exit()

if __name__ == "__main__":
    tmx_main_screen()
    start_game()
